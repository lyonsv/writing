#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md from the workspace's production dependencies
 * (`pnpm licenses list --prod --json`), plus the full IBM Plex Mono OFL text.
 * `pnpm notices` regenerates it; `pnpm notices --check` fails if it's stale
 * (run after adding or upgrading dependencies).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'THIRD_PARTY_NOTICES.md');
const json = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const byLicence = JSON.parse(json);
const ofl = readFileSync(path.join(root, 'apps/app/node_modules/@fontsource/ibm-plex-mono/LICENSE'), 'utf8').trim();

const lines = [
  '# Third-party notices',
  '',
  'Margin is MIT-licensed (see `LICENSE`). It ships or depends on the software below, under their own licences.',
  'Generated by `pnpm notices` from the production dependencies of the workspace; do not edit by hand.',
  '',
  '## IBM Plex Mono (bundled writing font)',
  '',
  'Margin bundles IBM Plex Mono, unmodified, from `@fontsource/ibm-plex-mono` (ADR 0004). It is licensed under the SIL Open Font License 1.1; the full licence follows.',
  '',
  '```text',
  ofl,
  '```',
  '',
  '## Electron',
  '',
  'The desktop app embeds Electron (MIT) and Chromium, whose licences ship inside the app bundle (`Margin.app/Contents/Resources/LICENSES.chromium.html` and `LICENSE`).',
  '',
  '## npm packages',
  '',
];
for (const licence of Object.keys(byLicence).sort()) {
  const pkgs = [...byLicence[licence]].sort((a, b) => a.name.localeCompare(b.name));
  lines.push(`### ${licence} (${pkgs.length})`, '', '| Package | Version | Homepage |', '|---|---|---|');
  for (const p of pkgs) {
    const versions = [...new Set(p.versions ?? [p.version])].sort().join(', ');
    const home = (p.homepage ?? '').replace(/^git\+/, '').replace(/\|/g, '%7C');
    lines.push(`| ${p.name} | ${versions} | ${home} |`);
  }
  lines.push('');
}
const text = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== text) {
    console.error('THIRD_PARTY_NOTICES.md is out of date: run pnpm notices');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote THIRD_PARTY_NOTICES.md (${Object.values(byLicence).flat().length} packages)`);
}
